"""V2: audit the *separate* post-hoc PF validation artifacts; never alter frozen D6.

Input generated by the existing validate_dr_pf.py (V1 proposal, V2 short SIS,
V3 20k/80k, V4 gate). Missing sections become NOT_RUN, never inferred PASS.
python v2_pf_reference_audit.py --out followup_runs/v2_001
"""
from __future__ import annotations

import argparse
from pathlib import Path

import common as C

DEFAULT = C.DIAG / "out" / "D5_PF_VALIDATION.json"


def audit(source: Path):
    if not source.is_file():
        return dict(status="NOT_RUN", sections={}, message="PF validation not found")
    j = C.IO.load_json(source)
    sections = {}
    for name in ("V1", "V2", "V3", "V4"):
        v = j.get(name)
        if not v:
            sections[name] = dict(status="NOT_RUN")
            continue
        if name == "V1":
            rows = {}
            for label, entry in v.items():
                p = entry["pf_vs_reference"]
                ok = (p["whitened_mean_diff_sq"] < .01 and
                      .95 <= p["cov_eig_min"] <= p["cov_eig_max"] <= 1.05)
                rows[label] = dict(compatible=ok, measurements=p)
            sections[name] = dict(status="COMPATIBLE" if all(
                x["compatible"] for x in rows.values()) else "REVIEW", rows=rows,
                caution="Single-step validation does not prove long-horizon PF accuracy")
        elif name == "V2":
            # Known separate limits: weighted SIS may have tiny ESS.
            rows = {}
            for label, entry in v.items():
                r = entry.get("pose", {})
                ess = entry.get("sis_ess_min")
                rows[label] = dict(measurements=r, sis_ess_min=ess,
                                   low_ess=bool(ess is not None and ess < 500))
            sections[name] = dict(status="REVIEW", rows=rows,
                                  caution="Compare ESS, PF mean/cov and rejuvenation on each route")
        elif name == "V3":
            rows = {}
            for label, entry in v.items():
                k = entry
                ratio = k.get("anees_80k", 0) / max(k.get("anees_20k", 0), 1e-12)
                rows[label] = dict(anees_ratio_80k_20k=ratio,
                                   enees_80k_under_20k=k.get("enees_80k_posterior_under_20k"),
                                   conditional_cov_ratio=k.get("cond_xy_cov_ratio_80k_over_20k"),
                                   heading_ratio=k.get("heading_var_ratio_80k_over_20k"))
            sections[name] = dict(status="DESCRIPTIVE", rows=rows,
                                  caution="ANEES alone does not certify posterior convergence")
        else:
            rows = {}
            for label, entry in v.items():
                rows[label] = dict(
                    anees_change=entry.get("anees_gated", 0) -
                                 entry.get("anees_ungated", 0),
                    gate_reject_frac=entry.get("gate_reject_frac"),
                    changed_strict_status=entry.get("consistent_gated") !=
                                          entry.get("consistent_ungated"))
            sections[name] = dict(status="DESCRIPTIVE", rows=rows,
                                  caution="Mixture-PF gate and EKF gate need not be identical")
    return dict(status="PARTIAL_VALIDATION" if any(
        v["status"] == "NOT_RUN" for v in sections.values()) else "AUDITED",
                sections=sections, source_sha256=C.sha256(source),
                note="Post-hoc V2 results do not change D6 criteria or PF definition")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", type=Path, default=DEFAULT)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    rep = audit(a.source)
    out = C.new_dir(a.out)
    C.write_json_new(out / "V2_PF_REFERENCE_AUDIT.json", rep)
    C.write_json_new(out / "V2_MANIFEST.json", C.provenance())
    print(rep["status"], {k: v["status"] for k, v in rep["sections"].items()})


if __name__ == "__main__":
    main()
