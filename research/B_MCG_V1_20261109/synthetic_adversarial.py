"""Deterministic wrong-reference counterexamples using a synthetic RF model.

This is an API/mechanism stress experiment. It is NOT empirical R2/R4/R5
evidence, a SourceFFD replay, a calibrated probability, or a prevalence estimate.
"""
from pathlib import Path
import argparse,json,csv
from dataclasses import asdict,replace
import numpy as np
from mcg import Config,profile_history,score_current,weights,covariance_update,wrap,motion_path
from test_mcg import SyntheticCore,SyntheticRF,fixture


def serial(x):
    if isinstance(x,np.ndarray):return x.tolist()
    if isinstance(x,(np.integer,np.floating,np.bool_)):return x.item()
    raise TypeError(type(x).__name__)


def assess(name,anchor,controls,t,hist_z,current_z,mu,R,cfg,truth,current_prior=None):
    profile=profile_history(SyntheticCore,SyntheticRF,None,anchor,controls,t,hist_z,mu[:-1],R,cfg)
    score=score_current(profile,current_z,mu[-1]);beta,status=weights(score,cfg)
    result={'name':name,'profile_reason':profile['reason'],'profile_status':profile['status'],
            'score_status':status,'scores':score['scores'],'beta':beta,'theta':profile['theta'],
            'target_span_sigma':profile['target_span_sigma'],'cost':profile['profile_cost'],
            'linearity_sigma':profile['linearity_sigma'],'rank':profile['rank'],
            'valid_channels':profile['valid_channels'],'config':asdict(cfg)}
    if current_prior is not None:
        h,H=SyntheticRF.batch(current_prior[None]);nu=current_z-h[0]-mu[-1]
        result['same_prior_actions']=[]
        for pxy in [.003,.01,.03]:
            P=np.diag([pxy,pxy,.01,.0001]);loss={}
            for key,b in [('SKIP',(0.,0.)),('B',(1.,1.)),('GUARD',beta)]:
                x,_,_,_,_=covariance_update(current_prior,P,H[0],nu,R[-1],b)
                loss[key]=np.array([np.sum((x[:2]-truth[:2])**2),float(wrap(x[2]-truth[2])**2)])
            gain=loss['SKIP']-loss['B'];lost=np.maximum(loss['GUARD']-loss['B'],0)
            fraction=[float(lost[i]/gain[i]) if gain[i]>1e-14 else None for i in range(2)]
            result['same_prior_actions'].append({'prior_xy_variance_m2':pxy,
                'loss_metric_order':['xy_squared_error_m2','heading_squared_error_rad2'],
                'loss':loss,'baseline_beneficial_gain':gain,'lost_beneficial_gain_ratio':fraction})
    return result


def run(out):
    out=Path(out);out.mkdir(parents=True,exist_ok=True)
    a,c,t,q,z,mu,R=fixture(26);cfg=Config()
    result={'scope':'SYNTHETIC_NON_SOURCEFFD_MECHANISM_STRESS',
            'configuration_sha256':cfg.digest(),
            'n_history':25,'window_s':5.,'current_truth':q[-1],
            'disclaimer':'No inference about real-world occurrence rate or R2/R4/R5 utility.',
            'cases':[]}
    # Main donor prior and the world never change across reference counterfactuals.
    prior=q[-1]+np.array([.25,.25,.1,0.])
    result['same_main_prior']=prior
    result['cases'].append(assess('CLEAN_REFERENCE_AND_HISTORY',a,c,t,z[:-1],z[-1],mu,R,cfg,q[-1],prior))
    for deg in [-20,-10,-5,5,10,20]:
        aa=a.copy();aa[2]+=np.deg2rad(deg)
        result['cases'].append(assess('WRONG_ANCHOR_YAW_%+d_DEG'%deg,aa,c,t,z[:-1],z[-1],mu,R,cfg,q[-1],prior))
    for dx,dy in [(.3,.3),(-.3,-.3),(.3,-.3),(-.3,.3)]:
        aa=a.copy();aa[:2]+=[dx,dy]
        result['cases'].append(assess('WRONG_ANCHOR_POSITION_%+.1f_%+.1f_M'%(dx,dy),aa,c,t,z[:-1],z[-1],mu,R,cfg,q[-1],prior))
    for bg in [-.006,.006]:
        aa=a.copy();aa[3]+=bg
        result['cases'].append(assess('WRONG_ANCHOR_BG_%+.3f_RAD_S'%bg,aa,c,t,z[:-1],z[-1],mu,R,cfg,q[-1],prior))

    # Correlated history is generated by a single rigid offset in the SAME
    # known observation model. Current target returns to the true-world RF.
    # This constructs an ambiguity witness; it is not measured RF physics.
    offset=np.array([.3,.3,.3,0.])
    hq,_=motion_path(SyntheticCore,a+offset,c);hz,_=SyntheticRF.batch(hq)
    result['contaminated_history_rigid_offset_units_m_m_rad_rad_s']=offset
    cases=[
        ('CONTAMINATED_HISTORY_CLEAN_TARGET',a,c,hz[:-1],cfg),
        ('ORACLE_TRUTH_ANCHOR_SAME_AS_ALREADY_CORRECT_ANCHOR',a,c,hz[:-1],cfg),
        ('ORACLE_EXACT_MOTION_SAME_AS_ALREADY_EXACT_MOTION',a,c,hz[:-1],cfg),
        ('ORACLE_CLEAN_HISTORY_ONLY',a,c,z[:-1],cfg),
        ('WIDER_PROFILE_BOUND_DIAGNOSTIC',a,c,hz[:-1],replace(cfg,bounds=(.8,.8,np.pi/3,np.pi/900))),
    ]
    for name,aa,cc,history,conf in cases:
        result['cases'].append(assess(name,aa,cc,t,history,z[-1],mu,R,conf,q[-1],prior))

    byname={x['name']:x for x in result['cases']}
    witness=byname['CONTAMINATED_HISTORY_CLEAN_TARGET']
    clean=byname['ORACLE_CLEAN_HISTORY_ONLY']
    result['mechanism_findings']={
        'incorrect_clean_target_attenuation_observed':bool(np.any(witness['beta']<1)),
        'correct_anchor_and_exact_motion_are_insufficient':bool(np.any(witness['beta']<1)),
        'replacing_only_history_restores_unattenuated_target':bool(np.all(clean['beta']==1)),
        'reason':'Finite-history alignment can be internally coherent and still wrong. The new correct RF differs from the wrong historical alignment.',
        'identification_limit':'Online history and a disagreeing current target alone do not identify which interval carries the RF bias.',
        'not_a_solution':'The truth/clean oracles are diagnostic and unavailable to runtime.',
    }
    (out/'SYNTHETIC_WRONG_REFERENCE.json').write_text(json.dumps(result,default=serial,indent=2,allow_nan=False)+'\n')
    fields=['name','profile_reason','score_status','beta_r','beta_s','score_r','score_s','score_joint','max_xy_lost_gain_ratio']
    with (out/'SYNTHETIC_WRONG_REFERENCE.csv').open('w',newline='') as f:
        writer=csv.DictWriter(f,fieldnames=fields);writer.writeheader()
        for x in result['cases']:
            vals=[a['lost_beneficial_gain_ratio'][0] for a in x.get('same_prior_actions',[])];vals=[v for v in vals if v is not None]
            writer.writerow({'name':x['name'],'profile_reason':x['profile_reason'],'score_status':x['score_status'],
                'beta_r':x['beta'][0],'beta_s':x['beta'][1],'score_r':x['scores'][0],'score_s':x['scores'][1],
                'score_joint':x['scores'][2],'max_xy_lost_gain_ratio':max(vals) if vals else ''})
    print(json.dumps({'scope':result['scope'],'cases':len(result['cases']),'findings':result['mechanism_findings'],
                      'witness_scores':witness['scores'],'witness_beta':witness['beta'],
                      'witness_xy_lost_gain_ratios':[x['lost_beneficial_gain_ratio'][0] for x in witness['same_prior_actions']]},default=serial))


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--out',required=True);run(p.parse_args().out)
