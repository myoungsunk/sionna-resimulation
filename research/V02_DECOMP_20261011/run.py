def consistent_world(seed,std,cfg):
    """Truth generated by the filter's own transition()/odometry_model() and noise laws."""
    rng=np.random.default_rng([20261011,seed,3003]);nominal=np.array([2.,.5,.2,0.,0.,0.]);x0=nominal+rng.normal(size=6)*std
    ds,ang=traj();b=cfg.wheel_base;x=x0.copy();truth=[x.copy()];d_m=np.zeros(N+1);g_m=np.zeros(N+1);o_m=np.zeros(N+1)
    for k in range(1,N+1):
        a=ang[k];u=ds[k];d_true=u+x0[5]*b*a/4;g_true=a*(1+x0[4])+x0[3]*DT
        xn,_,_=F.transition(x,d_true,g_true,DT,b)
        # sanity: transition must reproduce the intended arc with the true calibration
        o_true=F.odometry_model(x,d_true,g_true,DT,b)[0]
        nd=rng.normal(0,np.sqrt(cfg.k_s*abs(d_true)));ng=rng.normal(0,cfg.gyro_N_rad_sqrt_s*np.sqrt(DT))
        no=rng.normal(0,np.sqrt(cfg.k_theta*abs(o_true)+cfg.k_stheta*abs(d_true)))
        d_m[k]=d_true+nd;g_m[k]=g_true+ng;o_m[k]=o_true+no;x=xn;truth.append(x.copy())
    return np.array(truth),d_m,g_m,o_m,x0
